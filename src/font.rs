pub fn draw_char(
    fb: &mut [u32],
    screen_w: usize,
    screen_h: usize,
    x: i32,
    y: i32,
    c: char,
    color: u32,
    shadow: bool,
) {
    let glyph = get_glyph(c.to_ascii_uppercase());
    if shadow {
        draw_glyph_raw(fb, screen_w, screen_h, x + 1, y + 1, &glyph, COLOR_BLACK);
    }
    draw_glyph_raw(fb, screen_w, screen_h, x, y, &glyph, color);
}

fn draw_glyph_raw(
    fb: &mut [u32],
    screen_w: usize,
    screen_h: usize,
    x: i32,
    y: i32,
    glyph: &[u8; 7],
    color: u32,
) {
    for row in 0..7 {
        let py = y + row as i32;
        if py < 0 || py >= screen_h as i32 {
            continue;
        }
        let byte = glyph[row];
        for col in 0..5 {
            let px = x + col as i32;
            if px < 0 || px >= screen_w as i32 {
                continue;
            }
            if (byte & (1 << (4 - col))) != 0 {
                let idx = (py as usize) * screen_w + (px as usize);
                fb[idx] = color;
            }
        }
    }
}

pub fn draw_text(
    fb: &mut [u32],
    screen_w: usize,
    screen_h: usize,
    x: i32,
    y: i32,
    text: &str,
    color: u32,
    shadow: bool,
) {
    let mut cur_x = x;
    for c in text.chars() {
        draw_char(fb, screen_w, screen_h, cur_x, y, c, color, shadow);
        cur_x += 6;
    }
}
