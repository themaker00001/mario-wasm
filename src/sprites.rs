pub fn parse_sprite(lines: &[&str]) -> (usize, usize, Vec<u32>) {
    let h = lines.len();
    let w = if h > 0 { lines[0].len() } else { 0 };
    let mut pixels = Vec::with_capacity(w * h);

    for line in lines {
        for c in line.chars() {
            let col = match c {
                '.' => COLOR_TRANSPARENT,
                'R' => COLOR_RED,
                'B' => COLOR_MARIO_BLUE,
                'S' => COLOR_SKIN,
                'K' => COLOR_DARK_BROWN,
                'W' => COLOR_WHITE,
                'Y' => COLOR_GOLD,
                'y' => COLOR_YELLOW_LIGHT,
                'O' => COLOR_BRICK_ORANGE,
                'L' => COLOR_BRICK_LIGHT,
                'G' => COLOR_PIPE_DARK,
                'g' => COLOR_PIPE_LIGHT,
                'd' => COLOR_BUSH_DARK,
                'X' => COLOR_BLACK,
                'C' => COLOR_CASTLE_GRAY,
                'c' => COLOR_CASTLE_DARK,
                'm' => COLOR_GOOMBA_BODY,
                'M' => COLOR_GOOMBA_DARK,
                't' => COLOR_KOOPA_SHELL,
                'T' => COLOR_KOOPA_BELLY,
                _ => COLOR_TRANSPARENT,
            };
            pixels.push(col);
        }
    }
    (w, h, pixels)
}

pub struct SpriteData {
    pub width: usize,
    pub height: usize,
    pub pixels: Vec<u32>,
}

impl SpriteData {
    pub fn from_ascii(lines: &[&str]) -> Self {
        let (width, height, pixels) = parse_sprite(lines);
        Self { width, height, pixels }
    }

    pub fn draw(&self, fb: &mut [u32], screen_w: usize, screen_h: usize, x: i32, y: i32, flip_x: bool) {
        let sw = self.width;
        let sh = self.height;
        for sy in 0..sh {
            let py = y + sy as i32;
            if py < 0 || py >= screen_h as i32 {
                continue;
            }
            let row_idx = (py as usize) * screen_w;
            for sx in 0..sw {
                let px = x + sx as i32;
                if px < 0 || px >= screen_w as i32 {
                    continue;
                }
                let src_x = if flip_x { sw - 1 - sx } else { sx };
                let color = self.pixels[sy * sw + src_x];
                if (color >> 24) != 0 {
                    fb[row_idx + (px as usize)] = color;
                }
            }
        }
    }
}

